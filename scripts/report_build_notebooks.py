"""Generate the project notebooks: 01 data and EDA, 02 VisA GPU experiments, 03 MVTec AD 2, 04 results.

Notebooks are *generated* rather than hand-edited for the same reason the results
table is: a notebook that is edited in place accumulates hidden state, stale
outputs and cells that only ran once in an order nobody recorded. Regenerating
from this script guarantees the committed notebooks are exactly what the source
says, with no execution counts or outputs baked in.

    python scripts/report_build_notebooks.py

Both notebooks are **thin drivers** (docs/06 §1): they install the package and
call its API. No model code lives in a cell, because code in a notebook cannot
be tested, reviewed, or re-run six weeks later.
"""

from __future__ import annotations

import json
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parents[1] / "notebooks"


def md(*lines: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": _src(lines)}


def code(*lines: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": _src(lines),
    }


def _src(lines) -> list[str]:
    text = "\n".join(lines)
    out = text.splitlines(keepends=True)
    return out or [""]


def notebook(cells: list[dict], *, accelerator: str = "none") -> dict:
    # nbformat 4.5 requires a cell id; positional ids keep the output deterministic,
    # so the committed notebooks still match what this builder emits.
    cells = [{"id": f"cell-{i:03d}", **cell} for i, cell in enumerate(cells)]
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11"},
            "accelerator": "GPU" if accelerator == "gpu" else "None",
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


